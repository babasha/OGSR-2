#!/bin/bash
# Regenerates <module>/CMakeSources.cmake from the module's own .vcxproj, so the Linux CMake
# build's file list always matches what MSBuild compiles on Windows. Re-run this whenever the
# vcxproj's <ClCompile> item list changes (added/removed/excluded file).
#
# Usage: bash gen_module_sources.sh <module_dir> <vcxproj_name> <cmake_var_name> [extra_exclude_regex]
#   module_dir   : path to the module directory, relative to ogsr_engine/ (e.g. xrCore)
#   vcxproj_name : the .vcxproj filename inside module_dir (e.g. xrCore.vcxproj)
#   cmake_var_name: CMake list variable name to emit (e.g. XRCORE_SOURCES)
#   extra_exclude_regex: optional ERE; matching source paths are commented out with a TODO
#                        (e.g. files needing a third-party lib not wired up yet)
set -u
cd "$(dirname "$0")/.."   # -> ogsr_engine/
MODULE_DIR=$1
VCXPROJ=$2
VARNAME=$3
EXCLUDE_RE=${4:-}

cd "$MODULE_DIR"

respell() {
  local p=$1 cur=. out="" c hit
  IFS=/ read -ra parts <<< "$p"
  for c in "${parts[@]}"; do
    if [ "$c" = ".." ] || [ "$c" = "." ]; then hit=$c
    else hit=$(ls -1 "$cur" 2>/dev/null | grep -ixF -- "$c" | head -1); [ -z "$hit" ] && hit=$c; fi
    cur="$cur/$hit"; out="${out:+$out/}$hit"
  done
  echo "$out"
}

mapfile -t RAW < <(tr -d '\r' < "$VCXPROJ" | awk '
  /<ClCompile Include="/ { if (f != "") print f; match($0, /Include="[^"]*"/); f = substr($0, RSTART + 9, RLENGTH - 10)
                           if ($0 ~ /\/>/) { print f; f = "" }; next }
  f != "" && /ExcludedFromBuild>true/ { f = ""; next }
  f != "" && /<\/ClCompile>/ { print f; f = "" }
  END { if (f != "") print f }' | tr '\' '/')

OUT="CMakeSources.cmake"
{
  echo "# Auto-generated by cmake/gen_module_sources.sh from $VCXPROJ — do not hand-edit."
  echo "# Re-run: bash ../cmake/gen_module_sources.sh $MODULE_DIR $VCXPROJ $VARNAME${EXCLUDE_RE:+ '$EXCLUDE_RE'}"
  echo "set($VARNAME"
  for f in "${RAW[@]}"; do
    # Always respell, even when the path already resolves: on NTFS (Git Bash) `-e` succeeds for
    # any case, so the vcxproj's spelling would leak through and break on a case-sensitive FS.
    real="$(respell "$f")"
    if [ -n "$EXCLUDE_RE" ] && [[ "$real" =~ $EXCLUDE_RE ]]; then
      echo "    # TODO(linux-link): excluded, matched '$EXCLUDE_RE' — $real"
    else
      echo "    \"$real\""
    fi
  done
  echo ")"
} > "$OUT"
echo "wrote $MODULE_DIR/$OUT ($(grep -c '^    "' "$OUT") sources, $(grep -c '^    #' "$OUT") excluded)"
