// ---------------------------------------------------------------------------
// ⭐ПОВТОРНАЯ ОЦЕНКА СВОЙСТВ МИРА В ПЛАНИРОВЩИКЕ ЦЕЛЕЙ (GOAP).
//
// CProblemSolver::solve() устроен так:
//     if (actual()) return;      // <- ОЦЕНИВАЕТ эвалуаторы текущего состояния
//     m_current_state.clear();   // <- и ВЫБРАСЫВАЕТ всё, что только что посчитал
//     search(...)                // <- поиск оценивает те же свойства ЗАНОВО
// Значения эвалуаторов внутри ОДНОГО solve() меняться не могут -- поиск сам на
// это уже опирается (свойство, попавшее в m_current_state, второй раз не
// оценивается). Значит пара actual()+поиск честно считает одно и то же дважды.
//
// ⚠Почему это дорого именно здесь: у сталкеров эвалуаторы -- СКРИПТОВЫЕ
// (xr_meet, ogsm_hideout, rx_ai, xr_help_wounded, state_mgr_*), каждый вызов --
// вход в Lua-VM ценой 6-34 мкс. Профиль 19-09 показал по ~480 вызовов каждого
// за 5 секунд при ~570 апдейтах NPC, то есть ровно "раз на апдейт" -- и это
// после того, как половину уже сняли.
//
// Здесь -- счётчики (`goap_stats 1`) и сам кэш (`goap_eval_cache 1`), живущий
// РОВНО один solve(). Кэш отдельным кваром, чтобы A/B делался в одном прогоне,
// а не сравнением двух сборок.
// ---------------------------------------------------------------------------
// ⛔РЕЗУЛЬТАТ ЗАМЕРА 19-09-2026: ГИПОТЕЗА НЕ ПОДТВЕРДИЛАСЬ.
// Кордон/день, 60 fps, четыре чередующихся окна в одном прогоне:
//     solve()          1340 в секунду
//     из них с перестроением плана   5-6 (0.4%)
//     evaluate()       9400 в секунду
//     повторных        21-33 (0.3%)
//     фаза планировщика с кэшом и без него: 1.31/1.25 против 1.27/1.39 -- шум.
// ⭐Почему: actual() почти всегда возвращает true, то есть план остаётся
// годным и поиск НЕ ЗАПУСКАЕТСЯ. Двойная оценка в коде есть, но этот путь
// проходится раз на двести вызовов.
// ⇒ Квар use_cache оставлен ВЫКЛЮЧЕННЫМ и нужен только для повторения опыта.
// ⭐Что здесь ВСЁ-ТАКИ ценно: сами счётчики. 9400 опросов свойств мира
// в секунду на главном потоке ради ответа "план ещё годен?", и в 99.6%
// случаев ответ "да". Это тот же узор, что у предикатов ALife.
namespace GoapStats
{
extern int enabled;    // консольный `goap_stats`: счётчики + отчёт раз в 5 с
extern int use_cache;  // консольный `goap_eval_cache`: 1 = отдавать значение из памятки

extern unsigned g_solves;        // вызовов solve()
extern unsigned g_replans;       // из них с перестроением плана
extern unsigned g_eval_actual;   // оценок эвалуаторов из actual()
extern unsigned g_eval_search;   // оценок из поиска
extern unsigned g_hits;          // из них нашлись бы в памятке (повторные)

void Tick();  // зовётся из solve() при enabled; сама решает, пора ли печатать

// ---------------------------------------------------------------------------
// ⭐`goap_stats 2`: ВРЕМЯ по каждому условию / действию планировщика (11-10, бой Switch).
// Профиль главного в бою: ИИ сталкеров ~15% (C++ планировщик 9.4 + Lua-условия 5.4) --
// чтобы решать «кэшировать / переписать на C++ / реже думать», надо знать, КТО из
// условий и действий дорогой. Ключ = (вид, id, Lua-класс или C++-класс).
// Своё время (self): вложенные области (действие-планировщик → его solve → условия)
// вычитаются из родителя, поэтому столбцы складываются без двойного счёта.
// Lua-класс скриптового условия/действия ставит обёртка (script_*_wrapper.cpp) в
// SetLabel() -- для текущей, самой внутренней открытой области.
// ⚠Только главный поток (планировщик живёт там); стек глубиной 64.
// ---------------------------------------------------------------------------
enum ProfKind : u32
{
    PK_EVAL = 0,  // evaluate() условия: id = id свойства мира
    PK_EXEC,      // execute() действия: id = id действия
    PK_INIT,      // initialize()/finalize() действия
    PK_SOLVE,     // solve() минус условия = сам поиск/сверка (C++)
    PK_COUNT
};

void ProfEnter(ProfKind kind);
void ProfLeave(ProfKind kind, u32 id, const char* cpp_name, u64 dt_ns);
void SetLabel(ProfKind kind, const char* lua_class); // only if the innermost open scope is of this kind
u64 ProfNowNs();

class ProfScope
{
    u64 m_t0;
    const char* m_name;
    u32 m_id;
    ProfKind m_kind;
    bool m_on;

public:
    ProfScope(ProfKind kind, u32 id, const char* cpp_name) : m_t0(0), m_name(cpp_name), m_id(id), m_kind(kind), m_on(enabled >= 2)
    {
        if (m_on)
        {
            ProfEnter(kind);
            m_t0 = ProfNowNs();
        }
    }
    ~ProfScope()
    {
        if (m_on)
            ProfLeave(m_kind, m_id, m_name, ProfNowNs() - m_t0);
    }
    ProfScope(const ProfScope&) = delete;
    ProfScope& operator=(const ProfScope&) = delete;
};
}
