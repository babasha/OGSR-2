void Register()
{
    // Log at most once per process — Register() is called on every device
    // (re)create (alt-tab / resolution change), but the banner is build identity,
    // not per-device state.
    static bool s_done = false;
    if (s_done)
        return;
    s_done = true;

    const size_t n = sizeof(s_blob);
    const size_t klen = sizeof(s_key) - 1;  // drop the implicit NUL terminator

    string512 out;
    const size_t lim = (n < sizeof(out) - 1) ? n : sizeof(out) - 1;
    for (size_t i = 0; i < lim; ++i)
        out[i] = static_cast<char>(s_blob[i] ^ s_key[i % klen]);
    out[lim] = 0;

    Msg("[Vulkan] %s", out);
    Msg("[Vulkan] build fingerprint: 0x%016I64x", static_cast<u64>(fingerprint()));
}

