#pragma once

// ЦЕНА КАДРА В ЯДРО-МИЛЛИСЕКУНДАХ (консольный `cpu_budget 1`).
//
// ⭐ЗАЧЕМ ИМЕННО ТАКОЕ ЧИСЛО. Цель «60 fps на Switch» — это арифметика вида
// «кадр стоит X, на A57 он будет в 10-15 раз дороже, влезает ли в 16.7 мс на
// четырёх ядрах». Все приборы, которые до сих пор для этого использовались,
// меряют ВРЕМЯ СТЕНЫ: `[VK CPU]` — длительность фаз главного потока,
// lua_vm_watch — длительность внешнего входа в VM. Ни то, ни другое не есть
// процессорное время: поток, вытесненный внутри замеряемого участка, приносит
// в отчёт чужое время.
//
// 📏И это не теория. 18-09 два измерителя одного и того же — Lua — разошлись в
// ШЕСТЬ РАЗ (2.42 мс/кадр по потоковым часам против 0.41 по сумме pcall),
// потому что шестнадцать TTAPI-потоков ходят в одну lua_State без блокировки и
// вытесняют друг друга внутри замеряемой области. Пока это число не уточнено,
// любой вывод о бюджете Switch недоказуем.
//
// КАК. `QueryThreadCycleTime` по КАЖДОМУ потоку процесса раз в отчёт (не на
// горячем пути — перечисление тридцати потоков раз в пять секунд бесплатно).
// Это циклы, реально исполненные потоком, вытеснение в них не попадает.
// Плюс `QueryProcessCycleTime` как контрольная сумма.
//
// ⚠Циклы переводятся в миллисекунды по частоте TSC, которая калибруется ОДИН
// раз коротким спином (~2 мс) при первом включении. Число частоты печатается —
// если оно не похоже на номинал процессора, всей таблице верить нельзя.
// ⚠Поток, завершившийся между отчётами, уносит свои циклы с собой; сумма по
// потокам поэтому может быть чуть меньше процессной. Разница печатается.
namespace CpuBudget
{
extern int enabled;   // консольный `cpu_budget`: 1 = потоки, 2 = + фазы главного потока

// Раз в кадр из CRenderDevice::on_idle. Сам решает, пора ли печатать.
void Frame();

// Калибровка TSC (циклов в миллисекунду). Нужна всем, кто мерит циклами и
// печатает core-ms: калибровка одна на процесс, и второй её копии быть не должно.
double CyclesPerMs();

// ---------------------------------------------------------------------------
// ⭐РАСКЛАДКА ГЛАВНОГО ПОТОКА ПО ФАЗАМ В ЦИКЛАХ (`cpu_budget 2`).
//
// Зачем отдельно от `r_profiler`. Тот мерит ВРЕМЯ СТЕНЫ и сам стоит дорого:
// 19-09 замер при fpslock60 с `r_profiler 2` показал record 3.2-5.2 мс против
// 1.65 без него, а fps просел с 58 до 35 -- прибор перекрывал измеряемое.
// Здесь берутся ЦИКЛЫ потока (QueryThreadCycleTime), то есть:
//   - ожидание (фенс, join воркера, лимитер кадров) в цену НЕ попадает,
//     а именно она и нужна для вопроса "сколько РАБОТЫ на последовательном пути";
//   - цена самого прибора -- один вызов на границу фазы, десяток на кадр.
//
// Время СВОЁ, не суммарное: фазы вложены (планировщик внутри FrameMove), и
// вложенная фаза вычитается из объемлющей -- иначе сумма частей не сойдётся с
// целым, на чём эта задача уже спотыкалась (1.04 против 2.09 в июне... см.
// switch-60fps-target-plan).
// ⚠Считается ТОЛЬКО на главном потоке: tid запоминается в первом Frame().
// ---------------------------------------------------------------------------
enum Phase : int
{
    PH_FRAMEMOVE = 0, // seqFrame.Process -- вся движковая логика кадра
    PH_SCHED,         //   из неё: CSheduler::Update
    PH_UPDATECL,      //   из неё: CObjectList::Update (UpdateCL объектов)
    PH_SUBMIT2ND,     // отправка задачи второму потоку
    PH_RBEGIN,        // Begin() -- ожидание фенса и acquire
    PH_RECORD,        // seqRender.Process -- запись командных буферов
    PH_PRESENT,       // End() -- submit + present
    PH_WAIT2ND,       // ожидание второго потока
    PH_LIMITER,       // хвост лимитера кадров
    // --- фазы ВТОРОГО потока (та же задача TTAPI, тело лямбды в on_idle) ---
    PH_SOUND,         // g_sound_update.OnFrame
    PH_SEQPARALLEL,   //   в т.ч. обход реестра ALife (предикаты на Lua)
    PH_SCRIPTGC,      // сборка мусора LuaJIT
    PH_SEQFRAMEMT,    // PHWorld (физика) + сетевой процессор
    PH_COUNT
};

void PhaseEnter(Phase p);
void PhaseLeave(Phase p);

struct PhaseScope
{
    Phase p;
    explicit PhaseScope(Phase p_) : p(p_) { PhaseEnter(p_); }
    ~PhaseScope() { PhaseLeave(p); }
};
}
