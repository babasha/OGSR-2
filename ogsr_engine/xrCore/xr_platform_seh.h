#pragma once

// ---------------------------------------------------------------------------
// ШОВ xrCore/platform, шаг 2: SEH.
//
// `__try`/`__except`/`__finally` -- структурная обработка исключений MSVC.
// Ловит АППАРАТНЫЕ исключения (access violation, деление на ноль, брошенный
// C++-объект тоже идёт через тот же механизм на MSVC) вокруг хрупкого кода
// (Lua-биндинги, ИИ, сеть, физика, рендер-загрузчик), чтобы одна плохая
// правка мода не валила процесс целиком. У GCC/Clang этого механизма НЕТ.
//
// ⚠⚠ЭТО НЕ ПОЛНЫЙ ЭКВИВАЛЕНТ, а осознанный компромисс ради компиляции:
// - На MSVC (`_MSC_VER`) макросы разворачиваются В ТОЧНОСТИ в прежние
//   __try/__except -- поведение байт-в-байт то же, что было. Фильтр-выражение
//   (второй параметр `XR_SEH_EXCEPT`, часто зовущий `GetExceptionInformation()`)
//   вычисляется как раньше.
// - На GCC/Clang -- в try/catch(...), который ловит ТОЛЬКО C++-исключения
//   (throw). Аппаратный SIGSEGV/SIGFPE уронит процесс как обычно, а не
//   попадёт в catch: SEH не переводится в сигналы автоматически, для этого
//   нужен отдельный sigaction-обработчик (сделан НЕ здесь). Фильтр-выражение
//   на этой ветке синтаксически ПРИНИМАЕТСЯ, но НЕ ВЫЧИСЛЯЕТСЯ -- макрос его
//   отбрасывает, поэтому `GetExceptionInformation()`/`EXCEPTION_EXECUTE_HANDLER`
//   внутри него не должны существовать на этой платформе вообще.
// - Такое же деление уже стояло руками в `xrGame/script_engine_help.cpp`
//   (`#if !defined(_CPPUNWIND) __try ... #else try ...`) -- этот файл
//   намеренно НЕ трогается, он уже переносим сам по себе.
//
// ⚠`__finally` сюда не входит: оба живых места (`xrCore/xrDebugNew.cpp`)
// имеют ПУСТОЕ тело, портируются заменой на простой блок `{ ... }` прямо на
// месте (см. правки), отдельный макрос не оправдан для двух пустых тел.
// ---------------------------------------------------------------------------

#ifdef _MSC_VER
#define XR_SEH_TRY __try
#define XR_SEH_EXCEPT(filterExpr) __except (filterExpr)
#else
#define XR_SEH_TRY try
#define XR_SEH_EXCEPT(filterExpr) catch (...)
#endif
