#!/usr/bin/env python3
"""Bitmap font atlas for the RmlUi menu, in the engine's own format.

    textures\\ui\\fonts\\<name>.dds   white glyphs, coverage in alpha, mip-mapped
    textures\\ui\\fonts\\<name>.ini   [mb_symbol_coords] height = H; <codepoint> = x1, y1, x2

The engine draws every glyph as a cell-tall quad starting at (x1, y1), x2 - x1
wide (ui_rml.cpp, FontEngine::Load), so each glyph is rendered into a full-height
row at its ADVANCE width; ink that overhangs the advance is kept in the padding.

Source font: Roboto (SIL OFL 1.1, github.com/google/fonts/tree/main/ofl/roboto),
variable -- the weight is picked per atlas.

usage: make_rml_font.py Roboto.ttf out_dir name weight [cell=64]
needs: Pillow; ImageMagick (`magick`) for the DDS.
"""
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFont

ttf, out_dir, name, weight = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
CELL = int(sys.argv[5]) if len(sys.argv) > 5 else 64
PAD = 8          # between glyphs: mips must not bleed a neighbour in
ATLAS_W = 2048

chars = [chr(c) for c in range(0x20, 0x7F)]
chars += [chr(c) for c in range(0x410, 0x450)] + ["Ё", "ё"]   # А..я, Ё ё
chars += list("«»—–…№° ’“”„×•")

# size so that ascender+descender fills the cell
font = ImageFont.truetype(ttf, CELL)
try:
    font.set_variation_by_axes([weight, 100])   # wght, wdth (the order the font lists them)
except Exception as e:  # static font: weight is whatever the file is
    print("no variation axes:", e)
asc, desc = font.getmetrics()
size = int(CELL * CELL / (asc + desc))
font = ImageFont.truetype(ttf, size)
try:
    font.set_variation_by_axes([weight, 100])
except Exception:
    pass
asc, desc = font.getmetrics()
H = asc + desc

rects = {}
x, y = PAD, PAD
for ch in chars:
    adv = int(round(font.getlength(ch)))
    if x + adv + PAD > ATLAS_W:
        x, y = PAD, y + H + PAD
    rects[ch] = (x, y, x + adv)
    x += adv + 2 * PAD
atlas_h = 1
while atlas_h < y + H + PAD:
    atlas_h *= 2

img = Image.new("RGBA", (ATLAS_W, atlas_h), (255, 255, 255, 0))
alpha = Image.new("L", (ATLAS_W, atlas_h), 0)
d = ImageDraw.Draw(alpha)
for ch, (x1, y1, x2) in rects.items():
    if ch.strip():
        d.text((x1, y1), ch, font=font, fill=255)
img.putalpha(alpha)

png = f"{out_dir}/{name}.png"
img.save(png)
subprocess.check_call(["magick", png, "-define", "dds:compression=none", f"{out_dir}/{name}.dds"])

with open(f"{out_dir}/{name}.ini", "w", encoding="ascii") as f:
    f.write("; generated by _tools/make_rml_font.py from Roboto (SIL OFL 1.1)\n")
    f.write("[mb_symbol_coords]\n")
    f.write(f"height = {H}\n")
    for ch, (x1, y1, x2) in rects.items():
        f.write(f"{ord(ch):05d} = {x1}, {y1}, {x2}\n")
print(f"{name}: {len(rects)} glyphs, cell {H}, atlas {ATLAS_W}x{atlas_h}")
